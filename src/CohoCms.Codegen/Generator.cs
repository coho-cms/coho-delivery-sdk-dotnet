    /// <summary><c>Coho.cs</c>: what reads every type, the shape the runtime hydrates with, the model's source, and <c>AddCoho</c>.</summary>
    private static GeneratedFile ClientFile(TypeModel model, string @namespace, List<ContentType> types, Dictionary<string, string> names, List<string> warnings)
    {
        var readers = new List<(ContentType Type, string Member, string Generic)>();
        var members = new HashSet<string>(StringComparer.Ordinal);
        foreach (var type in types)
        {
            var member = Pascal(type.Slug);
            if (ReservedReaderNames.Contains(member))
            {
                warnings.Add($"Type '{type.Slug}' is read as coho.{member}Type, because coho.{member} is taken by the generated client.");
                member = $"{member}Type";
            }
            if (!members.Add(member))
            {
                throw new CodegenException($"Two types would both be read as coho.{member}; rename one of them");
            }
            var name = names[type.Slug];
            var order = type.Fields.Any(field => field.Sortable) ? $"{name}.SortBy" : "NoSortOrder";
            readers.Add((type, member, $"{name}, {order}"));
        }

        var kind = model.Source.Immutable ? "a tag" : "a branch, whose types can change";
        var o = new Lines();
        o.Add(Header);
        o.Add($"// Project {model.Source.Project}, ref {model.Source.Ref} ({kind}), schema {model.Source.SchemaHash}, type model {model.IrVersion}.");
        o.Add();
        o.Add("#nullable enable");
        o.Add();
        o.Add("using System;");
        o.Add("using System.Collections.Generic;");
        o.Add("using System.Collections.Immutable;");
        o.Add("using System.Threading;");
        o.Add("using System.Threading.Tasks;");
        o.Add("using CohoCms.Delivery;");
        o.Add("using Microsoft.Extensions.DependencyInjection;");
        o.Add();
        o.Add($"namespace {@namespace};");
        o.Add();
        o.Add("/// <summary>Typed reads of every content type, on the ref and in the locale the config names.</summary>");
        o.Add("/// <remarks>The delivery key comes from the app: this library reads no environment. Safe to share, for the life of the app.</remarks>");
        o.Add("public sealed class Coho");
        o.Add("{");
        o.Add(1, "private readonly ContentClient _content;");
        o.Add();
        o.Add(1, "public Coho(ContentConfig config, ClientOptions? options = null)");
        o.Add(2, ": this(new ContentClient(config, Shape, options))");
        o.Add(1, "{");
        o.Add(1, "}");
        o.Add();
        o.Add(1, "internal Coho(ContentClient content)");
        o.Add(1, "{");
        o.Add(2, "_content = content;");
        foreach (var (type, member, generic) in readers)
        {
            o.Add(2, $"{member} = content.Type<{generic}>({Literal(type.Slug)});");
        }
        o.Add(1, "}");
        foreach (var (type, member, generic) in readers)
        {
            o.Add();
            o.Add(1, Summary(type.Name, ""));
            o.Add(1, $"public TypeReader<{generic}> {member} {{ get; }}");
        }
        o.Add();
        o.Add(1, "/// <summary>The entry with this slug, whatever its type, or null. Match on its type to narrow it.</summary>");
        o.Add(1, "public Task<EntryBase?> BySlugAsync(string slug, ReadOptions? options = null, CancellationToken cancellationToken = default)");
        o.Add(1, "{");
        o.Add(2, "return _content.BySlugAsync(slug, options, cancellationToken);");
        o.Add(1, "}");
        o.Add();
        o.Add(1, "/// <summary>The entry with this id, whatever its type, or null. Match on its type to narrow it.</summary>");
        o.Add(1, "public Task<EntryBase?> ByIdAsync(string id, ReadOptions? options = null, CancellationToken cancellationToken = default)");
        o.Add(1, "{");
        o.Add(2, "return _content.ByIdAsync(id, options, cancellationToken);");
        o.Add(1, "}");
        o.Add();
        o.Add(1, "/// <summary>The entries that exist, sorted by id. Ids not on the ref are left out.</summary>");
        o.Add(1, "public Task<IReadOnlyList<EntryBase>> ByIdsAsync(IReadOnlyCollection<string> ids, ReadOptions? options = null, CancellationToken cancellationToken = default)");
        o.Add(1, "{");
        o.Add(2, "return _content.ByIdsAsync(ids, options, cancellationToken);");
        o.Add(1, "}");
        o.Add();
        ShapeOf(o, types, names);
        o.Add();
        o.Add(1, "/// <summary>Where these types came from, for reporting which release a build was made from.</summary>");
        o.Add(1, "public static class Source");
        o.Add(1, "{");
        o.Add(2, $"public const string Project = {Literal(model.Source.Project)};");
        o.Add();
        o.Add(2, $"public const string Ref = {Literal(model.Source.Ref)};");
        o.Add();
        o.Add(2, $"public const bool Immutable = {(model.Source.Immutable ? "true" : "false")};");
        o.Add();
        o.Add(2, $"public const string SchemaHash = {Literal(model.Source.SchemaHash)};");
        o.Add();
        o.Add(2, $"public const string TypeModelVersion = {Literal(model.IrVersion)};");
        o.Add(1, "}");
        o.Add("}");
        o.Add();
        o.Add("/// <summary>Registers <see cref=\"Coho\"/> with an app's services.</summary>");
        o.Add("public static class ContentServiceCollectionExtensions");
        o.Add("{");
        o.Add(1, "/// <summary>");
        o.Add(1, "/// One <see cref=\"Coho\"/> for the app, configured from the <c>COHO_*</c> values in its");
        o.Add(1, "/// configuration unless <paramref name=\"config\"/> says otherwise.");
        o.Add(1, "/// </summary>");
        o.Add(1, "/// <returns>The builder of the client's HttpClient, to add handlers to.</returns>");
        o.Add(1, "public static IHttpClientBuilder AddCoho(this IServiceCollection services, Func<IServiceProvider, ContentConfig>? config = null)");
        o.Add(1, "{");
        o.Add(2, "return services.AddCohoContent(Coho.Shape, content => new Coho(content), config);");
        o.Add(1, "}");
        o.Add("}");
        return new GeneratedFile("Coho.cs", o.ToString());
    }

    private static void ShapeOf(Lines o, List<ContentType> types, Dictionary<string, string> names)
    {
        o.Add(1, "/// <summary>What the runtime needs to hydrate each type: its links, the fields it always has, and how to read it.</summary>");
        if (types.Count == 0)
        {
            o.Add(1, "public static IReadOnlyDictionary<string, TypeShape> Shape { get; } = new Dictionary<string, TypeShape>();");
            return;
        }
        o.Add(1, "public static IReadOnlyDictionary<string, TypeShape> Shape { get; } = new Dictionary<string, TypeShape>");
        o.Add(1, "{");
        foreach (var type in types)
        {
            var links = type.Fields.Where(field => field.Kind == "reference").ToList();
            var always = type.Fields.Where(field => field.Always).Select(field => Literal(field.Id)).ToList();
            o.Add(2, $"[{Literal(type.Slug)}] = new TypeShape");
            o.Add(2, "{");
            if (links.Count > 0)
            {
                var entries = links.Select(field => $"[{Literal(field.Id)}] = LinkKind.{(field.Many ? "Many" : "One")}");
                o.Add(3, $"Links = new Dictionary<string, LinkKind> {{ {string.Join(", ", entries)} }}.ToImmutableDictionary(),");
            }
            if (always.Count > 0)
            {
                o.Add(3, $"Always = [{string.Join(", ", always)}],");
            }
            o.Add(3, $"Read = entry => new {names[type.Slug]}(entry),");
            o.Add(2, "},");
        }
        o.Add(1, "};");
    }

