    /// <summary><c>blogPost</c> becomes <c>BlogPost</c>. Slugs start lowercase, so no two types share a name.</summary>
    private static Dictionary<string, string> TypeNames(List<ContentType> types, List<string> warnings)
    {
        var names = new Dictionary<string, string>(StringComparer.Ordinal);
        var taken = new HashSet<string>(StringComparer.Ordinal);
        foreach (var type in types)
        {
            var name = Pascal(type.Slug);
            if (ReservedTypeNames.Contains(name))
            {
                warnings.Add($"Type '{type.Slug}' is named {name}Entry, because {name} is taken by the generated code.");
                name = $"{name}Entry";
            }
            if (!taken.Add(name))
            {
                throw new CodegenException($"Two types would both be named {name}; rename one of them");
            }
            names[type.Slug] = name;
        }
        return names;
    }

    /// <summary>Each field's property name, and the names of the types nested in the record.</summary>
    private static Dictionary<string, string> PropertyNames(ContentType type, string typeName, List<string> warnings)
    {
        var names = new Dictionary<string, string>(StringComparer.Ordinal);
        var nested = type.Fields.Where(IsChoice).Select(field => ChoiceName(Pascal(field.Id))).ToHashSet(StringComparer.Ordinal);
        var taken = new HashSet<string>(StringComparer.Ordinal);
        foreach (var field in type.Fields)
        {
            var name = Pascal(field.Id);
            if (ReservedFieldNames.Contains(name) || name == typeName || nested.Contains(name))
            {
                warnings.Add($"{type.Slug}.{field.Id} is {typeName}.{name}Field, because {name} is taken by the generated code.");
                name = $"{name}Field";
            }
            if (!taken.Add(name))
            {
                throw new CodegenException($"Two fields of {type.Slug} would both be {typeName}.{name}; rename one of them");
            }
            names[field.Id] = name;
        }
        return names;
    }

    /// <summary>Upper-cases the first letter: field ids and slugs are already camel case.</summary>
    private static string Pascal(string id) => id.Length == 0 ? id : char.ToUpperInvariant(id[0]) + id[1..];

    private static string ChoiceName(string property) => $"{property}Choice";

    /// <summary>
    /// A member name for a choice's value, such as <c>Landing</c> for <c>landing</c>, or null
    /// when the value makes none: it can still be used, as <c>new("…")</c>.
    /// </summary>
    private static string? ValueName(string value)
    {
        var name = new StringBuilder();
        var upper = true;
        foreach (var c in value)
        {
            if (char.IsAsciiLetterOrDigit(c))
            {
                name.Append(upper ? char.ToUpperInvariant(c) : c);
                upper = false;
            }
            else
            {
                upper = true;
            }
        }
        if (name.Length == 0)
        {
            return null;
        }
        return char.IsAsciiDigit(name[0]) ? $"Value{name}" : name.ToString();
    }

    /// <summary>Two paths a case-insensitive file system, such as macOS's or Windows', would write to one file.</summary>
    private static void SameFileCheck(List<GeneratedFile> files)
    {
        var seen = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        foreach (var file in files)
        {
            if (seen.TryGetValue(file.Path, out var other))
            {
                throw new CodegenException($"{other} and {file.Path} would be one file on a case-insensitive file system; rename one of their types");
            }
            seen[file.Path] = file.Path;
        }
    }

