using System.Globalization;
using System.Text;

namespace CohoCms.Codegen;

internal sealed record GeneratedFile(string Path, string Contents);

/// <param name="Warnings">Things to tell whoever ran the generator. Never fatal.</param>
internal sealed record Generated(IReadOnlyList<GeneratedFile> Files, IReadOnlyList<string> Warnings);

/// <summary>
/// The C# for a type model: a file per content type holding its record, such as
/// <c>BlogPost.cs</c>, and <c>Coho.cs</c>, the client that reads them all.
/// </summary>
/// <remarks>
/// A pure function of the model and the namespace, so the same model always gives the
/// same bytes and a drift check can compare them. Nothing about the generator's own
/// version is written, for the same reason.
/// </remarks>
internal static class Generator
{
    /// <summary>How every generated file starts, so a later run knows which files are its own to remove.</summary>
    public const string GeneratedMark = "// <auto-generated>\n// Generated by CohoCms.Codegen from the Coho type model.";

    private const string Header = GeneratedMark + " Do not edit: run `dotnet coho-codegen generate`.\n// </auto-generated>";

    private const string Indent = "    ";

    /// <summary>
    /// The type names the generated code defines or uses unqualified, nested types included,
    /// which hide a namespace's type of the same name. A content type whose name would be one
    /// of these is given <c>Entry</c> after it, so no project's types can shadow them.
    /// </summary>
    private static readonly HashSet<string> ReservedTypeNames =
    [
        "Coho", "ContentServiceCollectionExtensions", "SortBy", "Source",
        "ClientOptions", "ContentClient", "ContentConfig", "EntryBase", "EntryReader", "ISortOrder", "Linked", "LinkKind",
        "NoSortOrder", "ReadOptions", "RepeaterItem", "TypeReader", "TypeShape",
        "CancellationToken", "DateTimeOffset", "Dictionary", "Func", "IHttpClientBuilder", "IReadOnlyCollection",
        "IReadOnlyDictionary", "IReadOnlyList", "IServiceCollection", "IServiceProvider", "ImmutableDictionary",
        "JsonElement", "SetsRequiredMembers", "SetsRequiredMembersAttribute", "Task",
    ];

    /// <summary>The members of <c>Coho</c> beside its readers. A type read as one of these is read as <c>&lt;Name&gt;Type</c>.</summary>
    private static readonly HashSet<string> ReservedReaderNames =
    [
        "ByIdAsync", "ByIdsAsync", "BySlugAsync", "Coho", "Equals", "Finalize", "GetHashCode", "GetType", "MemberwiseClone",
        "Shape", "Source", "ToString",
    ];

    /// <summary>The members every entry record has. A field named as one of these is given <c>Field</c> after it.</summary>
    private static readonly HashSet<string> ReservedFieldNames =
    [
        "Deconstruct", "EqualityContract", "Equals", "Finalize", "GetHashCode", "GetType", "Id", "Locale", "MemberwiseClone",
        "PrintMembers", "Slug", "SortBy", "ToString", "Type",
    ];

    public static Generated Generate(TypeModel model, string @namespace)
    {
        var warnings = new List<string>();
        foreach (var warning in model.Warnings)
        {
            warnings.Add($"{warning.Type}.{warning.Field}: {warning.Message}");
        }
        if (!model.Source.Immutable)
        {
            warnings.Add($"Generated from '{model.Source.Ref}', a branch: its types can change. Release builds should name a tag.");
        }

        var types = model.Types.Keys.Order(StringComparer.Ordinal).Select(slug => model.Types[slug]).ToList();
        var names = TypeNames(types, warnings);
        var files = new List<GeneratedFile> { ClientFile(model, @namespace, types, names, warnings) };
        files.AddRange(types.Select(type => TypeFile(type, @namespace, names, warnings)));
        SameFileCheck(files);
        return new Generated(files, warnings);
    }

