    /// <summary>A one-line doc comment. Names are content, so they are escaped as XML.</summary>
    private static string Summary(string name, string note)
    {
        var text = string.Join(". ", new[] { Clean(name), note }.Where(part => part != ""));
        return $"/// <summary>{Xml(text)}</summary>";
    }

    private static string Clean(string name) => string.Join(' ', name.Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries));

    private static string Xml(string text) => text.Replace("&", "&amp;", StringComparison.Ordinal).Replace("<", "&lt;", StringComparison.Ordinal).Replace(">", "&gt;", StringComparison.Ordinal);

    /// <summary>A C# string literal.</summary>
    private static string Literal(string value)
    {
        var literal = new StringBuilder("\"");
        foreach (var c in value)
        {
            literal.Append(c switch
            {
                '"' => "\\\"",
                '\\' => "\\\\",
                '\n' => "\\n",
                '\r' => "\\r",
                '\t' => "\\t",
                _ when char.IsControl(c) => $"\\u{(int)c:x4}",
                _ => c.ToString(),
            });
        }
        return literal.Append('"').ToString();
    }

    /// <summary>Lines of a file, joined with <c>\n</c> and ending with one.</summary>
    private sealed class Lines
    {
        private readonly StringBuilder _text = new();

        public void Add(string line = "") => _text.Append(line).Append('\n');

        public void Add(int depth, string line) => Add(string.Concat(Enumerable.Repeat(Indent, depth)) + line);

        public override string ToString() => _text.ToString();
    }
